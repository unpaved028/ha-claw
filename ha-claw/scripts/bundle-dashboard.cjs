/**
 * bundle-dashboard.cjs – Bundles the UI sources into src/web/dashboard.ts.
 *
 * Reads:  src/web/ui/{dashboard.html,style.css,client.js}
 * Writes: src/web/dashboard.ts
 *
 * WHY INLINE EVERYTHING? Home Assistant Ingress maps URLs dynamically via
 * /api/hassio_ingress/<token>/. A browser cannot resolve relative <link> or
 * <script src> paths through that mapping, so the whole UI has to ship inside
 * a single HTML response.
 *
 * WHY A STRING ARRAY INSTEAD OF A TEMPLATE LITERAL? The payload contains
 * backticks, backslashes and ${...} sequences from the frontend JavaScript.
 * Emitting it as a TypeScript template literal required escaping those three
 * by hand in the right order, which broke repeatedly (v0.8.1–v0.8.5). Every
 * line now goes through JSON.stringify, which cannot be broken by payload
 * content, and the lines are joined back together at runtime. Keeping one
 * array entry per source line also keeps git diffs reviewable.
 *
 * Usage:
 *   node scripts/bundle-dashboard.cjs           # regenerate dashboard.ts
 *   node scripts/bundle-dashboard.cjs --check   # exit 1 if dashboard.ts is stale
 */

const fs = require('node:fs');
const path = require('node:path');

const addonRoot = path.resolve(__dirname, '..');
const uiDir = path.join(addonRoot, 'src', 'web', 'ui');
const outputPath = path.join(addonRoot, 'src', 'web', 'dashboard.ts');

/** Placeholder that client.js uses for the Ingress base path. */
const BASE_PATH_TOKEN = '__BASEPATH__';

const CSS_PLACEHOLDER = '/* __INLINE_CSS__ */';
const JS_PLACEHOLDER = '/* __INLINE_JS__ */';

/**
 * Insert `payload` at `placeholder`. The replacement is passed as a function so
 * that `$&`, `$$` and friends inside the payload are treated as literal text
 * rather than as replacement patterns.
 */
function inject(source, placeholder, payload, label) {
  if (!source.includes(placeholder)) {
    throw new Error(`Placeholder ${placeholder} for ${label} not found in dashboard.html`);
  }
  return source.replace(placeholder, () => payload);
}

function readSource(name) {
  const file = path.join(uiDir, name);
  if (!fs.existsSync(file)) {
    throw new Error(`Missing UI source file: ${path.relative(addonRoot, file)}`);
  }
  return fs.readFileSync(file, 'utf-8');
}

function build() {
  const css = readSource('style.css');
  const html = readSource('dashboard.html');
  const js = readSource('client.js');

  if (!js.includes(BASE_PATH_TOKEN)) {
    throw new Error(`client.js does not contain the ${BASE_PATH_TOKEN} placeholder`);
  }

  let assembled = inject(html, CSS_PLACEHOLDER, css, 'style.css');
  assembled = inject(assembled, JS_PLACEHOLDER, js, 'client.js');

  // Normalize line endings so the output is byte-identical on every platform.
  const lines = assembled.split(/\r?\n/);

  const header = [
    '/**',
    ' * dashboard.ts – HTML template for the HA-Claw Web UI.',
    ' *',
    ' * ⚠️  AUTO-GENERATED FILE – DO NOT EDIT MANUALLY!',
    ' *',
    ' * Generated by scripts/bundle-dashboard.cjs from:',
    ' *   - src/web/ui/dashboard.html  (HTML structure)',
    ' *   - src/web/ui/style.css       (CSS themes and styles)',
    ' *   - src/web/ui/client.js       (Frontend JavaScript)',
    ' *',
    ' * Edit those files, then run: npm run bundle',
    ' * (npm run build does it automatically via the prebuild hook.)',
    ' */',
    '',
    '/* eslint-disable */',
    '',
    `const BASE_PATH_TOKEN = ${JSON.stringify(BASE_PATH_TOKEN)};`,
    '',
    '/** Inlined UI payload – one array entry per source line. */',
    'const TEMPLATE_LINES: string[] = [',
  ];

  const body = lines.map(line => `  ${JSON.stringify(line)},`);

  const footer = [
    '];',
    '',
    "const TEMPLATE = TEMPLATE_LINES.join('\\n');",
    '',
    '/** Render the dashboard with the Ingress base path substituted in. */',
    'export function dashboardHtml(basePath: string): string {',
    '  return TEMPLATE.split(BASE_PATH_TOKEN).join(basePath);',
    '}',
    '',
  ];

  return {
    output: [...header, ...body, ...footer].join('\n'),
    stats: {
      css: css.split(/\r?\n/).length,
      html: html.split(/\r?\n/).length,
      js: js.split(/\r?\n/).length,
      total: lines.length,
    },
  };
}

function normalize(text) {
  return text.replace(/\r\n/g, '\n');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const { output, stats } = build();

  console.log(
    `Read style.css (${stats.css} lines), dashboard.html (${stats.html} lines), ` +
      `client.js (${stats.js} lines)`,
  );

  if (checkOnly) {
    const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf-8') : '';
    if (normalize(current) !== normalize(output)) {
      console.error(
        'dashboard.ts is out of date with src/web/ui/.\n' +
          'Run "npm run bundle" and commit the regenerated file.',
      );
      process.exit(1);
    }
    console.log('dashboard.ts is up to date.');
    return;
  }

  fs.writeFileSync(outputPath, output, 'utf-8');
  console.log(`Generated src/web/dashboard.ts (${stats.total} payload lines)`);
}

try {
  main();
} catch (err) {
  console.error(`bundle-dashboard failed: ${err.message}`);
  process.exit(1);
}
