let uiLang = 'de';

function uiT(key, vars) {
  const dict = I18N[uiLang] || I18N.de;
  let s = dict[key] ?? I18N.de[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      s = s.split('{' + k + '}').join(String(vars[k]));
    });
  }
  return s;
}

function toolDesc(name) {
  const table = uiLang === 'en' ? TOOL_DESC_EN : TOOL_DESC_DE;
  return table[name] || '';
}

function applyI18n() {
  document.documentElement.lang = uiLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = uiT(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = uiT(el.getAttribute('data-i18n-html'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', uiT(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', uiT(el.getAttribute('data-i18n-title')));
  });
}

function uiDateLocale() {
  return uiLang === 'en' ? 'en' : 'de-DE';
}

function setUiLang(lang) {
  uiLang = lang === 'en' ? 'en' : 'de';
  applyI18n();
  if (typeof renderNotifyMatrix === 'function') renderNotifyMatrix();
  if (typeof recognition !== 'undefined' && recognition) {
    recognition.lang = uiLang === 'en' ? 'en-US' : 'de-DE';
  }
}
